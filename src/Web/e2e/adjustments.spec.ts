import AxeBuilder from '@axe-core/playwright'
import { expect, test } from '@playwright/test'
import { adjustmentsApi, ownerPermissions, warehousePermissions } from './adjustments-api'
import { json, mockApi } from './mock-api'

test.describe('Estoque: ajuste com motivo e aprovação (EST-01b)', () => {
  test('almoxarife lança o ajuste na quantidade contada, com o reservado e o valor ao vivo (CA 2 e 4)', async ({ page }) => {
    const { api, calls } = adjustmentsApi()
    await mockApi(page, { ...api, 'GET /api/v1/me/permissions': (r) => json(r, warehousePermissions()) })
    await page.goto('/app/estoque/ajustes')
    await expect(page.getByText('Nenhum ajuste lançado.')).toBeVisible()
    await expect(page.getByText('Mostrando: Todos os ajustes')).toBeVisible()
    await page.getByRole('button', { name: 'Lançar ajuste' }).first().click()

    const dialog = page.getByRole('alertdialog')
    await expect(dialog.getByText('Sugerido')).toBeVisible()
    await expect(dialog.getByRole('radio', { name: 'Quantidade contada' })).toBeChecked()
    await dialog.getByRole('combobox', { name: 'Motivo' }).selectOption('Loss')
    await dialog.getByRole('combobox', { name: 'Adicionar item ao ajuste' }).click()
    await page.getByRole('option', { name: /MP-001/ }).click()
    const items = dialog.getByRole('list', { name: 'Itens do ajuste' })
    await expect(items).toContainText('Disponível 6 UN · sistema 10')

    const quantity = dialog.getByRole('textbox', { name: 'Quantidade contada de MP-001' })
    await quantity.fill('2')
    await expect(items.getByRole('alert')).toContainText('O saldo ficaria 2,0000 UN, abaixo do reservado (4,0000 UN) para OS.')
    await expect(items.getByRole('link', { name: 'Ver reservas do item' })).toBeVisible()
    await expect(dialog.getByRole('button', { name: 'Enviar para aprovação' })).toBeDisabled()

    await quantity.fill('8')
    await expect(items).toContainText('Diferença −2 UN')
    await expect(dialog.getByRole('group', { name: 'Impacto' })).toContainText('Faltas: R$ 25,00')
    await dialog.getByRole('radio', { name: 'Diferença' }).click()
    await expect(dialog.getByRole('alert').filter({ hasText: 'limpa as quantidades' })).toBeVisible()
    await dialog.getByRole('button', { name: 'Manter' }).click()
    await expect(dialog.getByRole('radio', { name: 'Quantidade contada' })).toBeChecked()

    await dialog.getByRole('button', { name: 'Enviar para aprovação' }).click()
    await expect(page.getByRole('status').filter({ hasText: 'Ajuste enviado para aprovação' }).first()).toBeVisible()
    expect(calls[0].body).toEqual({ locationId: 'alm', mode: 'Counted', reason: 'Loss', reasonDetail: null, lines: [{ itemId: 'i1', lotId: null, quantity: 8, unitId: null }] })
    await expect(page.getByRole('region', { name: 'Próximos passos' })).toContainText('Ver AJ-2026-0001')
  })

  test('o Proprietário aprova pelo link da notificação, com o saldo que mudou desde o envio (CA 3, 5 e 7)', async ({ page }) => {
    const { api, calls } = adjustmentsApi({ status: 'Pending' })
    await mockApi(page, { ...api, 'GET /api/v1/me/permissions': (r) => json(r, ownerPermissions()) })
    await page.goto('/app/estoque/ajustes')
    await expect(page.getByText('Mostrando: Aguardando você')).toBeVisible()
    await page.getByRole('button', { name: '1 notificações não lidas' }).click()
    await page.getByRole('button', { name: /Ajuste AJ-2026-0001 de Almoxarifado principal aguardando aprovação/ }).click()
    await expect(page).toHaveURL(/\/app\/estoque\/ajustes\/a1$/)
    await expect(page.getByText('Aguardando aprovação').first()).toBeVisible()

    await page.getByRole('button', { name: 'Aprovar ajuste' }).click()
    const approve = page.getByRole('alertdialog')
    const impact = approve.getByRole('group', { name: 'Impacto' })
    await expect(impact).toContainText('O saldo mudou desde o envio')
    await expect(impact).toContainText('MP-001: 11 → 8 UN (−3)')
    await expect(impact).toContainText('Faltas R$ 37,50')
    const results = await new AxeBuilder({ page }).analyze()
    expect(results.violations.filter((v) => v.impact === 'serious' || v.impact === 'critical').map((v) => v.id)).toEqual([])
    await approve.getByRole('button', { name: 'Aprovar ajuste' }).click()
    await expect(page.getByRole('status').filter({ hasText: 'Ajuste aprovado' }).first()).toBeVisible()
    expect(calls.at(-1)?.url).toContain('/adjustments/a1/approve')
    expect(calls.at(-1)?.body).toEqual({ comment: null, version: 1 })
    await expect(page.getByText(/Aprovado em .* por Ana Souza\. Para corrigir, lance outro ajuste ou estorne este\./)).toBeVisible()
    await expect(page.getByRole('region', { name: 'Próximos passos' })).toContainText('Gerar solicitação de compra')
    await expect(page.getByRole('button', { name: 'Aprovar ajuste' })).toHaveCount(0)
  })

  test('aba Decisão mostra quem lançou e quem aprovou, com a ajuda da aba', async ({ page }) => {
    const { api } = adjustmentsApi({ status: 'Approved' })
    await mockApi(page, { ...api, 'GET /api/v1/me/permissions': (r) => json(r, ownerPermissions()) })
    await page.goto('/app/estoque/ajustes/a1?aba=decisao')
    await expect(page.getByRole('tab', { name: 'Decisão' })).toHaveAttribute('aria-selected', 'true')
    await expect(page.getByText('Bruno Almoxarife ·').first()).toBeVisible()
    await expect(page.getByText(/Ana Souza ·/).first()).toBeVisible()
    await page.getByRole('tab', { name: 'Itens' }).click()
    await expect(page.getByRole('link', { name: 'MOV-2026-000031' })).toBeVisible()
  })

  test('a 400 px a lista fica com número, local, valor e situação e as linhas do ajuste em cartões', async ({ page }, info) => {
    test.skip(info.project.name !== 'celular')
    const { api } = adjustmentsApi({ status: 'Pending' })
    await mockApi(page, { ...api, 'GET /api/v1/me/permissions': (r) => json(r, ownerPermissions()) })
    await page.goto('/app/estoque/ajustes?filtro=todos')
    await expect(page.getByRole('link', { name: 'AJ-2026-0001' })).toBeVisible()
    await expect(page.getByRole('columnheader', { name: 'Modo' })).toBeHidden()
    await expect(page.getByRole('columnheader', { name: 'Diferença' })).toBeVisible()
    await page.getByRole('button', { name: /detalhes de AJ-2026-0001/ }).click()
    await expect(page.getByText(/Quantidade contada · 1 item · Bruno Almoxarife/)).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth)).toBeLessThanOrEqual(0)

    await page.getByRole('button', { name: 'Lançar ajuste' }).first().click()
    const dialog = page.getByRole('alertdialog')
    const box = await dialog.boundingBox()
    expect(box?.width).toBeGreaterThanOrEqual(399)
    await dialog.getByRole('combobox', { name: 'Adicionar item ao ajuste' }).click()
    await page.getByRole('option', { name: /MP-001/ }).click()
    await expect(dialog.getByRole('list', { name: 'Itens do ajuste' }).getByRole('listitem')).toHaveCount(1)
    await dialog.getByText('Físico e reservado').click()
    await expect(dialog.getByText(/Físico 10 UN · Reservado para OS 4/)).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth)).toBeLessThanOrEqual(0)
  })
})
